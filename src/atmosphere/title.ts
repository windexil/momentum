function seasonByDate(date?: string): string | null {
  if (!date) return null;
  const m = Number(date.slice(5, 7));
  if (!m) return null;
  return m === 12 || m <= 2 ? "зима" : m <= 5 ? "весна" : m <= 8 ? "лето" : "осень";
}

/** Слова из списка в порядке их первого появления в тексте. */
function found(t: string, list: [string, string][]): string[] {
  return list
    .map(([stem, noun]) => ({ noun, at: t.indexOf(stem) }))
    .filter((x) => x.at !== -1)
    .sort((a, b) => a.at - b.at)
    .map((x) => x.noun);
}

export function makeDayTitle(opts: { text: string; place: Place; themes: string[]; date?: string }): string {
  const t = ` ${opts.text.toLowerCase().replace(/ё/g, "е")} `;
  const items: string[] = [];
  const add = (w: string | null | undefined) => {
    if (w && !items.some((x) => x.toLowerCase() === w.toLowerCase())) items.push(w);
  };
  if (opts.place !== "room") add(PLACE_NOUN[opts.place]);
  else add(THEME_NOUN[opts.themes[0]] ?? "дом");
  add(found(t, TIME)[0] ?? seasonByDate(opts.date));
  for (const d of found(t, DETAIL)) {
    if (items.length >= 3) break;
    add(d);
  }
  for (const th of opts.themes) {
    if (items.length >= 3) break;
    add(THEME_NOUN[th]);
  }
  add(seasonByDate(opts.date));
  const parts = items.slice(0, 3);
  const s = parts.length === 3 ? `${parts[0]}, ${parts[1]} и ${parts[2]}` : parts.join(" и ");
  return s.charAt(0).toUpperCase() + s.slice(1);
}
