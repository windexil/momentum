// из записи по одному правилу, чтобы все названия звучали в одном тоне:
//   «Место, время и деталь» — три существительных, 3–5 слов.
//   Место   — где прошёл день (море, лес, город, парк…), иначе главная тема.
//   Время   — время суток или сезон из текста, иначе сезон по дате записи.
//   Деталь  — первая конкретная вещь или человек из текста (какао, друзья, гирлянды…),
//             иначе настроение дня (уют, тишина, радость…).
// Пример: «Гуляли по осеннему парку, пили какао» → «Парк, осень и какао».

